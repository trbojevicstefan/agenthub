'use strict';
// Generates ui/theme-light.css from ui/style.css: every hard-coded dark-theme color gets a light-theme counterpart
// with the same hue and inverted lightness. Rules use :where(body[data-theme="light"]) so they carry the original
// selector's specificity and never outrank the hand-tuned body[data-theme="light"] rules in style.css.
// Run after changing colors in style.css: node scripts/generate-light-theme.cjs
const fs=require('node:fs'),path=require('node:path');
const root=path.resolve(__dirname,'..'),source=fs.readFileSync(path.join(root,'ui/style.css'),'utf8').replace(/\r\n/g,'\n');
const PROPS=/^(color|background|background-color|border|border-color|border-top|border-right|border-bottom|border-left|border-top-color|border-right-color|border-bottom-color|border-left-color|outline|outline-color|fill|stroke|caret-color|accent-color)$/;
const hexToRgb=h=>{h=h.slice(1);if(h.length<=4)h=[...h].map(c=>c+c).join('');return [0,2,4,6].map(i=>i<h.length?parseInt(h.slice(i,i+2),16):255);};
const toHex=v=>'#'+v.map(x=>Math.round(Math.max(0,Math.min(255,x))).toString(16).padStart(2,'0')).join('');
function rgbToHsl([r,g,b]){r/=255;g/=255;b/=255;const max=Math.max(r,g,b),min=Math.min(r,g,b),l=(max+min)/2;if(max===min)return [0,0,l];const d=max-min,s=l>.5?d/(2-max-min):d/(max+min);const h=max===r?(g-b)/d+(g<b?6:0):max===g?(b-r)/d+2:(r-g)/d+4;return [h/6,s,l];}
function hslToRgb([h,s,l]){if(!s)return [l,l,l].map(v=>v*255);const q=l<.5?l*(1+s):l+s-l*s,p=2*l-q,f=t=>{t=(t+1)%1;return t<1/6?p+(q-p)*6*t:t<1/2?q:t<2/3?p+(q-p)*(2/3-t)*6:p;};return [f(h+1/3),f(h),f(h-1/3)].map(v=>v*255);}
function invert(hex,prop){
  const [r,g,b,a]=hexToRgb(hex),[h,s,l]=rgbToHsl([r,g,b]);
  // Only dark-theme-shaped colors flip: light text, dark surfaces and borders. Dark text on accent fills stays.
  if(prop==='color'||prop==='caret-color'||prop==='fill'?l<.5:l>.62)return hex;
  // Text needs extra weight on a light surface; surfaces and borders mirror their dark lightness.
  const text=prop==='color'||prop==='caret-color'||prop==='fill';
  const next=text?Math.min(.42,(1-l)*.72):prop.startsWith('border')||prop.startsWith('outline')||prop==='stroke'?Math.max(.62,Math.min(.9,1-l*.9)):Math.max(.8,1-l);
  const out=hslToRgb([h,Math.min(s,text?.55:.35),next]);
  return toHex(hex.length===5||hex.length===9?[...out,a]:out);
}
function convert(decls){
  const out=[];
  for(const decl of decls.split(';')){
    const i=decl.indexOf(':');if(i<0)continue;const prop=decl.slice(0,i).trim().toLowerCase(),value=decl.slice(i+1).trim();
    if(!PROPS.test(prop)||!/#[0-9a-f]{3,8}\b/i.test(value))continue;
    out.push(`${prop}:${value.replace(/#[0-9a-f]{3,8}\b/gi,m=>invert(m,prop))}`);
  }
  return out.join(';');
}
// Minimal CSS walker for this stylesheet: plain rules and @media blocks; @keyframes are left alone.
function walk(css){
  let i=0,out='';
  while(i<css.length){
    const open=css.indexOf('{',i);if(open<0)break;
    const head=css.slice(i,open).replace(/\/\*[\s\S]*?\*\//g,'').trim();
    if(head.startsWith('@')){
      let depth=1,j=open+1;while(depth&&j<css.length){if(css[j]==='{')depth++;else if(css[j]==='}')depth--;j++;}
      if(head.startsWith('@media')){const inner=walk(css.slice(open+1,j-1));if(inner)out+=`${head}{${inner}}\n`;}
      i=j;continue;
    }
    const close=css.indexOf('}',open),body=css.slice(open+1,close);i=close+1;
    if(head.includes('data-theme')||/xterm|::backdrop|:root\b/.test(head))continue;
    const decls=convert(body);if(!decls)continue;
    const selectors=head.split(',').map(s=>s.trim()).filter(Boolean).map(s=>s.startsWith('body')?`:where(body[data-theme="light"])${s.slice(4)}`:`:where(body[data-theme="light"]) ${s}`);
    out+=`${selectors.join(',')}{${decls}}\n`;
  }
  return out;
}
const css=`/* Generated by scripts/generate-light-theme.cjs from style.css. Do not edit by hand. */\n${walk(source)}`;
const target=path.join(root,'ui/theme-light.css');
if(process.argv.includes('--check')){if(fs.readFileSync(target,'utf8').replace(/\r\n/g,'\n')!==css){console.error('ui/theme-light.css is stale. Run: node scripts/generate-light-theme.cjs');process.exit(1);}}
else{fs.writeFileSync(target,css);console.log(`Wrote ui/theme-light.css (${css.split('\n').length-2} rules).`);}
